CREATE VIEW shop.customer_stats AS
SELECT c.id, c.full_name, c.country, count(o.id) AS orders, coalesce(sum(o.total), 0) AS revenue
FROM shop.customers c LEFT JOIN shop.orders o ON o.customer_id = c.id
GROUP BY c.id;

CREATE MATERIALIZED VIEW analytics.daily_events AS
SELECT date_trunc('day', occurred_at) AS day, kind, count(*) AS n
FROM analytics.events GROUP BY 1, 2;

CREATE FUNCTION shop.order_total(p_order bigint) RETURNS numeric
LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(quantity * unit_price), 0) FROM shop.order_items WHERE order_id = p_order;
$$;

CREATE FUNCTION shop.touch_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.total := shop.order_total(NEW.id);
    RETURN NEW;
END $$;

CREATE TRIGGER orders_touch BEFORE UPDATE ON shop.orders FOR EACH ROW EXECUTE FUNCTION shop.touch_order();

