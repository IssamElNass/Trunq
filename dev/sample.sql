-- Sample database used for developing / demoing Trunq.
DROP SCHEMA IF EXISTS shop CASCADE;
DROP SCHEMA IF EXISTS analytics CASCADE;
CREATE SCHEMA shop;
CREATE SCHEMA analytics;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE shop.order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled');

CREATE TABLE shop.customers (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    full_name text NOT NULL,
    country char(2) NOT NULL DEFAULT 'NL',
    is_vip boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    preferences jsonb
);
COMMENT ON TABLE shop.customers IS 'People who can place orders';
COMMENT ON COLUMN shop.customers.is_vip IS 'Gets free shipping';

CREATE TABLE shop.products (
    id serial PRIMARY KEY,
    sku text NOT NULL UNIQUE,
    name text NOT NULL,
    price numeric(10,2) NOT NULL CHECK (price >= 0),
    tags text[] NOT NULL DEFAULT '{}',
    stock integer NOT NULL DEFAULT 0,
    description text
);

CREATE TABLE shop.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES shop.customers(id) ON DELETE CASCADE,
    status shop.order_status NOT NULL DEFAULT 'pending',
    total numeric(12,2) NOT NULL DEFAULT 0,
    placed_at timestamptz NOT NULL DEFAULT now(),
    ship_to inet,
    tracking uuid DEFAULT gen_random_uuid()
);
CREATE INDEX orders_customer_idx ON shop.orders (customer_id);
CREATE INDEX orders_placed_idx ON shop.orders (placed_at DESC);

CREATE TABLE shop.order_items (
    order_id bigint NOT NULL REFERENCES shop.orders(id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES shop.products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL,
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE analytics.events (
    id bigserial PRIMARY KEY,
    occurred_at timestamptz NOT NULL,
    kind text NOT NULL,
    user_id bigint,
    payload jsonb NOT NULL DEFAULT '{}'
) ;

